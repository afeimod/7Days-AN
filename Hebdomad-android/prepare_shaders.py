"""Prepare MIT-licensed upstream filters for GLES 2.0; no bitwise GLSL ops."""
import pathlib,re,json
root=pathlib.Path(__file__).resolve().parent
out={}
for name in ['hq4x','xbr-lv2']:
 s=(root/'third_party/filters'/f'{name}.glsl').read_text()
 s=re.sub(r'^#version.*$', '',s,flags=re.M)
 s=re.sub(r'^#pragma.*$', '',s,flags=re.M)
 # Pixel neighbourhoods at HD/ultrawide widths need more than mediump UVs.
 s=s.replace('mediump','highp')
 if name=='xbr-lv2':
  s=s.replace('#define XBR_SCALE 3.0','#define XBR_SCALE 4.0').replace('FragColor.xyz = res;','FragColor = vec4(res,1.0);')
  s=re.sub(r'mul\(\s*rgbw\s*,\s*mat4x3\(\s*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*\)\s*\)',r'vec4(dot(rgbw,\1),dot(rgbw,\2),dot(rgbw,\3),dot(rgbw,\4))',s)
  s=re.sub(r'mul\(\s*mat4x3\(([^)]+)\),\s*y_weight \* Y\s*\)',lambda m:'vec4('+','.join('dot('+v.strip()+',y_weight * Y)' for v in m[1].split(','))+')',s)
  s=s.replace('vec4 delta_u = delta_l.yxwz;','const vec4 delta_u = vec4(1.0/XBR_SCALE,0.5/XBR_SCALE,1.0/XBR_SCALE,0.5/XBR_SCALE);')
 s=s.replace('TexCoord.xy * 1.0001','TexCoord.xy')
 out[name]=s
header='// Generated by prepare_shaders.py. Upstream shader sources and HQ4x LUT.\n'
for name,s in out.items():header+='static const char *'+name.replace('-','_')+'=R"FILTER('+s+')FILTER";\n'
lut=(root/'third_party/filters/hq4x-lut.rgba.z').read_bytes()
header+='static const unsigned char hq4x_lut[]={'+chr(10)
for i in range(0,len(lut),24):header+=','.join(map(str,lut[i:i+24]))+','+chr(10)
header+='};'+chr(10)
(root/'native/filter_shaders.h').write_text(header)
print('Generated GLES2 shaders')
